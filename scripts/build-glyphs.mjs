// One-off generator for the vector lettering used inside the 3D drawings.
// The output is committed, so this does not run on Netlify. To regenerate:
//
//   npm i --no-save fontkit hersheytext @fontsource/archivo-black
//   node scripts/build-glyphs.mjs
//
// 1. src/experience/data/lettering.ts — single-stroke plotter lettering (Hershey "futural").
// 2. src/experience/data/numerals.ts  — outlined digits traced from Archivo Black.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import * as fontkit from 'fontkit';

const require = createRequire(import.meta.url);
const r = (n) => +n.toFixed(3);

// ── 1. Hershey single-stroke lettering ───────────────────────────────────────
const hershey = JSON.parse(readFileSync(require.resolve('hersheytext/hersheytext.min.json'), 'utf8'));
const CAP = 21; // cap height in Hershey units; baseline sits at y = 22
const glyphs = {};
hershey.futural.chars.forEach((ch, i) => {
  const char = String.fromCharCode(33 + i);
  const strokes = [];
  for (const part of ch.d.split('M').map((s) => s.trim()).filter(Boolean)) {
    const nums = part.replace(/L/g, ' ').trim().split(/[\s,]+/).map(Number);
    const pts = [];
    for (let k = 0; k < nums.length; k += 2) pts.push(r(nums[k] / CAP), r((22 - nums[k + 1]) / CAP));
    if (pts.length >= 4) strokes.push(pts);
  }
  glyphs[char] = { w: r((ch.o * 2) / CAP), s: strokes };
});
glyphs[' '] = { w: 0.62, s: [] };

writeFileSync(
  new URL('../src/experience/data/lettering.ts', import.meta.url),
  `// Generated by scripts/build-glyphs.mjs — do not edit by hand.
// Single-stroke lettering from the Hershey fonts ("futural"), originally created by
// Dr. A. V. Hershey at the U.S. Naval Weapons Laboratory and distributed by the U.S.
// National Bureau of Standards. JSON port: hersheytext (MIT, James T).
// Units: cap height = 1, baseline at y = 0. \`w\` is the advance, \`s\` the pen strokes (x, y pairs).
export interface Letter { w: number; s: number[][] }
export const LETTERING: Record<string, Letter> = ${JSON.stringify(glyphs)};
`,
);

// ── 2. Outlined numerals from Archivo Black ──────────────────────────────────
const font = fontkit.create(readFileSync(require.resolve('@fontsource/archivo-black/files/archivo-black-latin-400-normal.woff2')));
const cap = font.capHeight;
const sample = (cmds) => {
  const loops = [];
  let cur = null;
  let px = 0, py = 0;
  const push = (x, y) => { cur.push(r(x / cap), r(y / cap)); px = x; py = y; };
  for (const { command, args } of cmds) {
    if (command === 'moveTo') { cur = []; loops.push(cur); push(args[0], args[1]); }
    else if (command === 'lineTo') push(args[0], args[1]);
    else if (command === 'quadraticCurveTo') {
      const [cx, cy, x, y] = args; const x0 = px, y0 = py;
      for (let i = 1; i <= 6; i++) { const t = i / 6, u = 1 - t; push(u * u * x0 + 2 * u * t * cx + t * t * x, u * u * y0 + 2 * u * t * cy + t * t * y); }
    } else if (command === 'bezierCurveTo') {
      const [c1x, c1y, c2x, c2y, x, y] = args; const x0 = px, y0 = py;
      for (let i = 1; i <= 8; i++) { const t = i / 8, u = 1 - t; push(u * u * u * x0 + 3 * u * u * t * c1x + 3 * u * t * t * c2x + t * t * t * x, u * u * u * y0 + 3 * u * u * t * c1y + 3 * u * t * t * c2y + t * t * t * y); }
    }
  }
  // drop the duplicated closing point; loops are closed by the renderer
  return loops.map((l) => (l.length > 4 && l[0] === l[l.length - 2] && l[1] === l[l.length - 1] ? l.slice(0, -2) : l)).filter((l) => l.length >= 6);
};
const numerals = {};
for (const ch of '0123456789') {
  const g = font.glyphForCodePoint(ch.codePointAt(0));
  numerals[ch] = { w: r(g.advanceWidth / cap), s: sample(g.path.commands) };
}
writeFileSync(
  new URL('../src/experience/data/numerals.ts', import.meta.url),
  `// Generated by scripts/build-glyphs.mjs — do not edit by hand.
// Digit outlines traced from Archivo Black (Omnibus-Type, SIL Open Font License 1.1).
// Units: cap height = 1, baseline at y = 0. Each entry in \`s\` is a closed loop (x, y pairs).
import type { Letter } from './lettering';
export const NUMERALS: Record<string, Letter> = ${JSON.stringify(numerals)};
`,
);
console.log('lettering:', Object.keys(glyphs).length, 'glyphs · numerals:', Object.keys(numerals).length);
